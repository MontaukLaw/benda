/* 从中间件参数区读取一个无符号参数，并累计读取结果。 */
static uint32_t read_parameter(uint32_t parameter_id, bool *all_reads_succeeded) {
	uint32_t value = 0u;
	cy_capsense_status_t status = Cy_CapSense_GetParam(
		parameter_id,
		&value,
		&cy_capsense_tuner,
		&cy_capsense_context);

	if (status != CY_CAPSENSE_STATUS_SUCCESS) {
		*all_reads_succeeded = false;
	}
	return value;
}

/* 让后续扫描重新装载已经修改的Sensor Frame。 */
static void invalidate_repeat_scan(void) {
	cy_capsense_context.ptrInternalContext->repeatScanEn = CY_CAPSENSE_DISABLE;
	cy_capsense_context.ptrCommonContext->status &=
		(uint32_t)~CY_CAPSENSE_MW_STATE_WD_SCAN_MASK;
}

/* 判断当前逻辑通道是否是对应Widget第一次出现的位置。 */
static bool is_first_widget_channel(uint32_t channel) {
	uint32_t previous_channel;

	for (previous_channel = 0u; previous_channel < channel; previous_channel++) {
		if (channel_widget_ids[previous_channel] == channel_widget_ids[channel]) {
			return false;
		}
	}
	return true;
}

/* 在首次扫描前同步中间件配置与每个Sensor Frame的固定采样参数。 */
bool CapSenseChannelConfig_ApplyFixedAll(
	uint16_t nsub,
	uint16_t tx_clk_div,
	uint8_t ref_cdac) {
	uint32_t channel;
	bool success = true;

	if ((nsub == 0u) || (tx_clk_div == 0u) ||
		(ref_cdac < CY_CAPSENSE_CAL_REF_CDAC_MIN_CODE) ||
		(CY_CAPSENSE_NOT_BUSY != Cy_CapSense_IsBusy(&cy_capsense_context))) {
		return false;
	}

	for (channel = 0u; channel < DEVICE_SENSOR_CHANNEL_COUNT; channel++) {
		uint32_t slot_id;
		uint32_t *scan_control;
		uint32_t *sensor_control;
		uint32_t *cdac_control;

		if (is_first_widget_channel(channel)) {
			if (CY_CAPSENSE_STATUS_SUCCESS != Cy_CapSense_SetParam(
					channel_nsub_param_ids[channel], nsub,
					&cy_capsense_tuner, &cy_capsense_context)) {
				success = false;
			}
			if (CY_CAPSENSE_STATUS_SUCCESS != Cy_CapSense_SetParam(
					channel_tx_clk_param_ids[channel], tx_clk_div,
					&cy_capsense_tuner, &cy_capsense_context)) {
				success = false;
			}
			if (CY_CAPSENSE_STATUS_SUCCESS != Cy_CapSense_SetParam(
					channel_ref_cdac_param_ids[channel], ref_cdac,
					&cy_capsense_tuner, &cy_capsense_context)) {
				success = false;
			}
		}

		slot_id = cy_capsense_context.ptrWdConfig[channel_widget_ids[channel]].firstSlotId +
			channel_sensor_ids[channel];
		scan_control = &cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_SCAN_CTL_INDEX];
		sensor_control = &cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_CTL_INDEX];
		cdac_control = &cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_CDAC_CTL_INDEX];

		*scan_control &= ~MSCLP_SNS_SNS_SCAN_CTL_NUM_SUB_CONVS_Msk;
		*scan_control |= (((uint32_t)nsub - 1u) <<
			MSCLP_SNS_SNS_SCAN_CTL_NUM_SUB_CONVS_Pos) &
			MSCLP_SNS_SNS_SCAN_CTL_NUM_SUB_CONVS_Msk;
		*sensor_control &= ~MSCLP_SNS_SNS_CTL_SENSE_DIV_Msk;
		*sensor_control |= (((uint32_t)tx_clk_div - 1u) <<
			MSCLP_SNS_SNS_CTL_SENSE_DIV_Pos) &
			MSCLP_SNS_SNS_CTL_SENSE_DIV_Msk;
		*cdac_control &= ~MSCLP_SNS_SNS_CDAC_CTL_SEL_RE_Msk;
		*cdac_control |= ((uint32_t)ref_cdac <<
			MSCLP_SNS_SNS_CDAC_CTL_SEL_RE_Pos) &
			MSCLP_SNS_SNS_CDAC_CTL_SEL_RE_Msk;
	}

	if (success && (CY_CAPSENSE_STATUS_SUCCESS !=
		Cy_CapSense_InitializeCic2Rate(&cy_capsense_context))) {
		success = false;
	}
	if (success && (CY_CAPSENSE_STATUS_SUCCESS !=
		Cy_CapSense_InitializeCic2Shift(&cy_capsense_context))) {
		success = false;
	}

	if (success) {
		for (channel = 0u; channel < DEVICE_SENSOR_CHANNEL_COUNT; channel++) {
			if (!is_first_widget_channel(channel)) {
				continue;
			}
			if (CY_CAPSENSE_STATUS_SUCCESS != Cy_CapSense_InitializeMaxRaw(
					channel_widget_ids[channel], &cy_capsense_context)) {
				success = false;
				break;
			}
		}
	}

	invalidate_repeat_scan();
	return success;
}

/* 同时读取配置参数和实际扫描帧，识别参数未同步到硬件的情况。 */
bool CapSenseChannelConfig_ReadAll(
	capsense_channel_config_t configs[DEVICE_SENSOR_CHANNEL_COUNT]) {
	uint32_t channel;
	bool all_reads_succeeded = true;

	if (configs == NULL) {
		return false;
	}

	for (channel = 0u; channel < DEVICE_SENSOR_CHANNEL_COUNT; channel++) {
		uint32_t slot_id;
		uint32_t scan_control;
		uint32_t sensor_control;
		uint32_t cdac_control;

		configs[channel].widget_id = channel_widget_ids[channel];
		configs[channel].sensor_id = channel_sensor_ids[channel];
		configs[channel].configured_nsub = (uint16_t)read_parameter(
			channel_nsub_param_ids[channel], &all_reads_succeeded);
		configs[channel].configured_tx_clk_div = (uint16_t)read_parameter(
			channel_tx_clk_param_ids[channel], &all_reads_succeeded);
		configs[channel].configured_ref_cdac = (uint8_t)read_parameter(
			channel_ref_cdac_param_ids[channel], &all_reads_succeeded);
		configs[channel].max_raw_count = (uint16_t)read_parameter(
			channel_max_raw_param_ids[channel], &all_reads_succeeded);

		slot_id = cy_capsense_context.ptrWdConfig[channel_widget_ids[channel]].firstSlotId +
			channel_sensor_ids[channel];
		scan_control = cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_SCAN_CTL_INDEX];
		sensor_control = cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_CTL_INDEX];
		cdac_control = cy_capsense_context.ptrSensorFrameContext[
			(slot_id * CY_CAPSENSE_SENSOR_FRAME_SIZE) + CY_CAPSENSE_SNS_CDAC_CTL_INDEX];

		configs[channel].hardware_nsub = (uint16_t)(
			((scan_control & MSCLP_SNS_SNS_SCAN_CTL_NUM_SUB_CONVS_Msk) >>
			 MSCLP_SNS_SNS_SCAN_CTL_NUM_SUB_CONVS_Pos) + 1u);
		configs[channel].hardware_tx_clk_div = (uint16_t)(
			((sensor_control & MSCLP_SNS_SNS_CTL_SENSE_DIV_Msk) >>
			 MSCLP_SNS_SNS_CTL_SENSE_DIV_Pos) + 1u);
		configs[channel].hardware_ref_cdac = (uint8_t)(
			(cdac_control & MSCLP_SNS_SNS_CDAC_CTL_SEL_RE_Msk) >>
			MSCLP_SNS_SNS_CDAC_CTL_SEL_RE_Pos);
	}

	return all_reads_succeeded;
}
